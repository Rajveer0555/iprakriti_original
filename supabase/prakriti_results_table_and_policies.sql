create table if not exists public.prakriti_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  vata int not null default 0,
  pitta int not null default 0,
  kapha int not null default 0,
  final_prakriti text not null,
  created_at timestamptz not null default now()
);

alter table public.prakriti_results enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.prakriti_results to authenticated;

drop policy if exists "Users can view their own prakriti results" on public.prakriti_results;
create policy "Users can view their own prakriti results"
on public.prakriti_results
for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can insert their own prakriti results" on public.prakriti_results;
create policy "Users can insert their own prakriti results"
on public.prakriti_results
for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own prakriti results" on public.prakriti_results;
create policy "Users can update their own prakriti results"
on public.prakriti_results
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own prakriti results" on public.prakriti_results;
create policy "Users can delete their own prakriti results"
on public.prakriti_results
for delete
to authenticated
using (auth.uid() = user_id);
